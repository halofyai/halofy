#!/usr/bin/env node
/**
 * Builds src/skills/default-content.ts from the curated skill pack at
 * repo-root halomem-skills/<key>/SKILL.md (YAML frontmatter with `name` and
 * `description` plus a markdown body). Run it after editing the pack:
 *
 *   node scripts/build-default-skills.mjs
 *
 * The pack is reviewed product content, so it is bundled into the build as
 * embedded strings — neither dist/ nor the Docker image may depend on a
 * runtime fs path outside kernel/. Both this script and its output are
 * checked in.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const packDir = path.resolve(here, "../../halomem-skills");
const outFile = path.resolve(here, "../src/skills/default-content.ts");

// Mirrors SKILL_KEY_PATTERN in src/skills/store.ts.
const KEY_PATTERN = /^[a-z0-9][a-z0-9._-]{0,199}$/;

function unquote(value) {
  return value.replace(/^"(.*)"$/, "$1").replace(/^'(.*)'$/, "$1");
}

function parseSkillMd(raw, dir) {
  // Normalize line endings so the generated file is identical on every
  // checkout platform (the repo is edited on CRLF and LF hosts).
  const text = raw.replace(/\r\n/g, "\n");
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`${dir}: missing YAML frontmatter`);
  const fields = {};
  for (const line of match[1].split("\n")) {
    const m = /^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$/.exec(line);
    if (m) fields[m[1]] = unquote(m[2].trim());
  }
  const name = fields.name ?? "";
  const description = fields.description ?? "";
  if (!KEY_PATTERN.test(name)) {
    throw new Error(`${dir}: frontmatter name '${name}' is not a valid skill key`);
  }
  if (description.length === 0) throw new Error(`${dir}: missing frontmatter description`);
  const definition = match[2].replace(/^\n+/, "").replace(/\s+$/, "");
  if (definition.length === 0) throw new Error(`${dir}: empty markdown body`);
  return { skillKey: name, name, description, definition };
}

const dirs = (await readdir(packDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const skills = [];
for (const dir of dirs) {
  const raw = await readFile(path.join(packDir, dir, "SKILL.md"), "utf8");
  skills.push(parseSkillMd(raw, dir));
}
if (new Set(skills.map((s) => s.skillKey)).size !== skills.length) {
  throw new Error("duplicate skill keys in the pack");
}

const output = `/**
 * GENERATED by scripts/build-default-skills.mjs from the curated skill pack
 * at repo-root halomem-skills/<key>/SKILL.md — do not edit by hand. Re-run
 * the generator after changing the pack and check in the result.
 *
 * Each entry's definition is the SKILL.md markdown body WITHOUT the YAML
 * frontmatter; the download lane (renderSkillMarkdown in store.ts)
 * reassembles frontmatter from the catalog row itself.
 */

export interface DefaultSkillContent {
  skillKey: string;
  name: string;
  description: string;
  definition: string;
}

export const DEFAULT_SKILLS: readonly DefaultSkillContent[] = ${JSON.stringify(skills, null, 2)};
`;

await writeFile(outFile, output);
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${skills.length} default skills)`);
